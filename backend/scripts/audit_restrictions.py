"""Audit, from the code itself, that no agent or API route can send, spend, book, or commit anything.

    python -m backend.scripts.audit_restrictions

Builds the app and a workflow's tool registry on a throwaway database (no model calls, no network), then writes
docs/evidence/report/restrictions_audit.md:
  - every API route that changes data, with any name that suggests sending or spending flagged for review
  - every tool an agent can be given, each agent's allow-list, and whether any prohibited action is reachable
  - an attempt to register every prohibited action as a tool (each must be refused)
  - the pytest results of the restriction tests
"""

from __future__ import annotations

import dataclasses
import re
import subprocess
import sys
import tempfile
from pathlib import Path

from backend.app.agents.registry import AGENT_SPECS
from backend.app.core.config import get_settings
from backend.app.core.env import REPO_ROOT
from backend.app.safety.policy import PROHIBITED_ACTIONS
from backend.app.tools.registry import ProhibitedActionError, ToolKind, ToolRegistry, ToolSpec

RISKY = re.compile(r"send|e-?mail|pay|transfer|book|purchase|contract|wire|disburse|allocat|commit|approve_donation|schedule|publish|forward",
                   re.IGNORECASE)
TESTS = [
    "tests/test_boss_outreach.py::test_no_sending_and_no_spending_capability_exists",
    "tests/test_boss_outreach.py::test_a_draft_cannot_contain_an_invented_email_or_phone",
    "tests/test_boss_outreach.py::test_review_statuses_and_edits_persist",
    "tests/test_boss_outreach.py::test_finance_is_consulted_only_with_financial_access",
    "tests/test_adversarial.py::test_B_asking_to_email_100_organizations_sends_nothing",
    "tests/test_adversarial.py::test_D_a_workflow_cannot_spend_past_its_budget",
    "tests/test_adversarial.py::test_D2_concurrent_calls_cannot_slip_past_the_budget",
    "tests/test_adversarial.py::test_every_agent_has_an_enforced_allow_list_and_scope",
    "tests/test_permissions.py::test_member_blocked_from_financial_and_donor_data",
    "tests/test_permissions.py::test_donations_are_flagged_for_review_not_contacted",
]


def main() -> None:
    from backend.app.agents.runtime import RunContext
    from backend.app.ai.budget import WorkflowBudget
    from backend.app.ai.router import ModelRouter
    from backend.app.core.permissions import permissions_for
    from backend.app.main import create_app
    from backend.app.tools.catalog import build_tool_registry

    tmp = Path(tempfile.mkdtemp(prefix="sam-audit-"))
    settings = dataclasses.replace(get_settings(), database_path=tmp / "audit.db")
    app = create_app(settings, verify_models=False)
    out = ["# Restrictions audit: no sending, no spending, no binding commitments", "",
           "Generated by `python -m backend.scripts.audit_restrictions` from the code itself, on a throwaway database. No model calls.", ""]

    # 1. API routes that change data
    rows, flagged = [], []
    for path, ops in sorted(app.openapi()["paths"].items()):  # every route, including nested routers
        for method, op in ops.items():
            if method.upper() not in ("POST", "PUT", "PATCH", "DELETE"):
                continue
            name = (op.get("operationId") or "").split("_api_")[0]
            hit = bool(RISKY.search(path) or RISKY.search(name))
            rows.append((method.upper(), path, name, hit))
            if hit:
                flagged.append((path, name))
    out += [f"## 1. API routes that change data ({len(rows)})", "",
            "Routes whose path or handler name contains a word like send, email, pay, transfer, book, purchase, contract, commit, schedule, "
            "publish, or forward are flagged. A flag means *look closer*, not *unsafe*.", "",
            "| Method | Path | Handler | Flagged |", "|---|---|---|---|"]
    out += [f"| {m} | `{p}` | `{n}` | {'**yes**' if h else ''} |" for m, p, n, h in rows]
    out += ["", f"Flagged: {len(flagged)}." + (" Each is explained below." if flagged else ""), ""]

    # 2. Tools reachable by agents
    with app.state.db.session() as s:
        from backend.app.db.models import AgentRun
        run = AgentRun(organization_id=1, user_id=1, workflow_type="auto", request_text="audit", status="running", strategy="auto")
        s.add(run)
        s.commit()
        run_id = run.id
    ctx = RunContext(run_id=run_id, organization_id=1, user_id=1, user_permissions=permissions_for("chair"), strategy="auto",
                     research_mode="synthetic", db=app.state.db, router=ModelRouter("openai"), budget=WorkflowBudget(1, 5),
                     settings=settings, llm=None)
    registry = build_tool_registry(ctx)
    tools = registry.names()
    reachable_prohibited = sorted(set(tools) & set(PROHIBITED_ACTIONS))
    risky_tools = [t for t in tools if RISKY.search(t)]
    out += [f"## 2. Tools an agent can be given ({len(tools)})", "", ", ".join(f"`{t}`" for t in tools), "",
            f"- Prohibited actions registered as tools: **{len(reachable_prohibited)}** {reachable_prohibited or ''}",
            f"- Tool names suggesting sending or spending: **{len(risky_tools)}** {risky_tools or ''}", "",
            "| Agent | Allowed tools | Any outside the registry? | Any prohibited? |", "|---|---|---|---|"]
    for spec in AGENT_SPECS:
        outside = sorted(set(spec.allowed_tools) - set(tools))
        bad = sorted(set(spec.allowed_tools) & set(PROHIBITED_ACTIONS))
        out.append(f"| {spec.display_name} | {', '.join(f'`{t}`' for t in spec.allowed_tools) or '(none)'} | {outside or 'no'} | {bad or 'no'} |")

    # 3. Registering a prohibited action is refused
    probe = ToolRegistry()
    refused = []
    for name in PROHIBITED_ACTIONS:
        try:
            probe.register(ToolSpec(name=name, description="audit probe", kind=next(iter(ToolKind)), func=lambda **_: None))
        except ProhibitedActionError:
            refused.append(name)
    out += ["", f"## 3. Registering a prohibited action as a tool ({len(PROHIBITED_ACTIONS)} names)", "",
            f"Refused: **{len(refused)} of {len(PROHIBITED_ACTIONS)}**.", "",
            "| Name | Meaning | Refused |", "|---|---|---|"]
    out += [f"| `{n}` | {m} | {'yes' if n in refused else '**NO**'} |" for n, m in PROHIBITED_ACTIONS.items()]

    # 4. Restriction tests
    proc = subprocess.run([sys.executable, "-m", "pytest", "-o", "addopts=", "-q", "-rA", *TESTS], cwd=REPO_ROOT, capture_output=True, text=True)
    lines = [ln for ln in proc.stdout.splitlines() if ln.startswith(("PASSED", "FAILED", "ERROR"))]
    summary = proc.stdout.strip().splitlines()[-1] if proc.stdout.strip() else "no output"
    out += ["", "## 4. Restriction tests (pytest, scripted model)", "", f"Result: **{summary}**", ""] + [f"- {ln}" for ln in lines]
    (REPO_ROOT / "docs" / "evidence" / "report").mkdir(parents=True, exist_ok=True)
    (REPO_ROOT / "docs" / "evidence" / "report" / "restrictions_audit.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"routes {len(rows)} (flagged {len(flagged)}: {flagged}); tools {len(tools)}; prohibited reachable {reachable_prohibited}; "
          f"refused {len(refused)}/{len(PROHIBITED_ACTIONS)}; tests: {summary}")


if __name__ == "__main__":
    main()
